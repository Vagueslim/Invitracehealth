import { readFile, writeFile } from 'node:fs/promises';
import { basename, extname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = resolve(root, 'dist');
const source = resolve(dist, 'th/coda/index.html');
const destination = resolve(root, 'Invitracehealth-portfolio.html');

const mimeTypes = {
  '.css': 'text/css',
  '.jpeg': 'image/jpeg',
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

async function dataUri(assetPath) {
  if (!/^\/assets\/[a-zA-Z0-9._-]+$/.test(assetPath)) {
    throw new Error(`Unexpected asset path: ${assetPath}`);
  }
  const mime = mimeTypes[extname(assetPath)];
  if (!mime) throw new Error(`Unknown asset type: ${assetPath}`);
  const bytes = await readFile(resolve(dist, assetPath.slice(1)));
  return `data:${mime};base64,${bytes.toString('base64')}`;
}

let html = await readFile(source, 'utf8');
const cssPath = html.match(/<link rel="stylesheet" crossorigin href="(\/assets\/[^\"]+\.css)">/)?.[1];
const modulePaths = [...html.matchAll(/<script type="module" crossorigin src="(\/assets\/[^\"]+\.js)"><\/script>/g)].map(match => match[1]);
if (!cssPath || modulePaths.length !== 2) throw new Error('Unexpected production HTML structure');

let css = await readFile(resolve(dist, cssPath.slice(1)), 'utf8');
const cssAssets = [...new Set([...css.matchAll(/url\((['"]?)(\/assets\/[^)'\"]+)\1\)/g)].map(match => match[2]))];
for (const assetPath of cssAssets) css = css.replaceAll(assetPath, await dataUri(assetPath));
html = html.replace(/<link rel="stylesheet" crossorigin href="\/assets\/[^\"]+\.css">/, `<style>${css}</style>`);

const imageAssets = [...new Set([...html.matchAll(/<img\b[^>]*\bsrc="(\/assets\/[^\"]+)"/g)].map(match => match[1]))];
for (const assetPath of imageAssets) html = html.replaceAll(`src="${assetPath}"`, `src="${await dataUri(assetPath)}"`);

const menuPath = modulePaths.find(path => basename(path).startsWith('site-menu-'));
const pagePath = modulePaths.find(path => basename(path).startsWith('coda-'));
if (!menuPath || !pagePath) throw new Error('Missing Coda scripts');
let menuJs = await readFile(resolve(dist, menuPath.slice(1)), 'utf8');
let pageJs = await readFile(resolve(dist, pagePath.slice(1)), 'utf8');
menuJs = menuJs.replace(/export\{L as a,g as i\};?\s*$/, '');
pageJs = pageJs.replace(/^import\{a as s,i as f\}from"\.\/site-menu-[^\"]+\.js";/, 'const s=L,f=g;');
if (pageJs.startsWith('import') || menuJs.includes('export{')) throw new Error('Could not inline the built scripts');
html = html.replace(/\s*<script type="module" crossorigin src="\/assets\/[^\"]+\.js"><\/script>/g, '');
html = html.replace('</body>', `<script>${menuJs}\n${pageJs}</script></body>`);

const favicon = await readFile(resolve(root, 'public/favicon.png'));
html = html.replace('href="../../favicon.png"', `href="data:image/png;base64,${favicon.toString('base64')}"`);
html = html.replace(/href="\.\/([^\"]*)"/g, (_, route) => {
  if (!route) return 'href="./Invitracehealth-portfolio.html"';
  return `href="./th/coda/${route}index.html"`;
});
html = html.replaceAll('href="../../coda/"', 'href="./coda/index.html"');

html = html.replace('<!-- Generated by scripts/generate-pages.mjs. Do not edit directly. -->',
  '<!-- Offline Thai homepage export. Regenerate with npm run build, then node scripts/export-coda-home.mjs. -->');
await writeFile(destination, html, 'utf8');
console.log(`Wrote ${destination} (${Math.round(Buffer.byteLength(html) / 1024)} KiB)`);
